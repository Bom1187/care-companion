create or replace function public.admin_review_moderation_appeal(
  appeal_id bigint,
  decision text,
  review_note text default null
)
returns public.moderation_appeals
language plpgsql
security definer set search_path = public
as $$
declare
  changed_appeal public.moderation_appeals;
begin
  if not public.is_admin() then
    raise exception 'Only admins can review appeals';
  end if;
  if decision not in ('approved', 'rejected') then
    raise exception 'Invalid appeal decision';
  end if;

  update public.moderation_appeals
  set status = decision,
      admin_note = nullif(trim(review_note), ''),
      reviewed_by = auth.uid(),
      reviewed_at = now()
  where id = appeal_id and status = 'pending'
  returning * into changed_appeal;

  if changed_appeal.id is null then
    raise exception 'Pending appeal not found';
  end if;

  if decision = 'approved' then
    update public.profiles
    set moderation_type = null, moderation_until = null, moderation_note = null, updated_at = now()
    where id = changed_appeal.user_id;
  end if;

  perform public.write_audit_event(
    'moderation_appeal_reviewed',
    changed_appeal.user_id,
    jsonb_build_object('appeal_id', appeal_id, 'decision', decision, 'note', review_note)
  );
  return changed_appeal;
end;
$$;

