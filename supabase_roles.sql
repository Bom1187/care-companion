create or replace function public.admin_set_user_role(
  target_user_id uuid,
  new_role text
)
returns public.profiles
language plpgsql
security definer set search_path = public
as $$
declare
  changed_profile public.profiles;
  role_value public.user_role;
begin
  if not public.is_admin() then
    raise exception 'Only admins can change roles';
  end if;

  begin
    role_value := new_role::public.user_role;
  exception when invalid_text_representation then
    raise exception 'Invalid role';
  end;

  update public.profiles
  set role = role_value, updated_at = now()
  where id = target_user_id
  returning * into changed_profile;

  if changed_profile.id is null then
    raise exception 'Profile not found';
  end if;

  perform public.write_audit_event(
    'role_changed',
    target_user_id,
    jsonb_build_object('new_role', new_role)
  );

  return changed_profile;
end;
$$;

revoke all on function public.admin_set_user_role(uuid, text) from public;
grant execute on function public.admin_set_user_role(uuid, text) to authenticated;

create or replace function public.admin_set_member_moderation(
  target_user_id uuid,
  action_type text,
  duration_minutes integer,
  moderation_reason text default null
)
returns public.profiles
language plpgsql
security definer set search_path = public
as $$
declare
  changed_profile public.profiles;
begin
  if not public.is_admin() then
    raise exception 'Only admins can moderate members';
  end if;

  if action_type not in ('ban', 'timeout', 'clear') then
    raise exception 'Invalid moderation action';
  end if;

  if action_type <> 'clear' and (duration_minutes is null or duration_minutes < 1) then
    raise exception 'Duration must be at least one minute';
  end if;

  if action_type = 'clear' then
    update public.profiles
    set moderation_type = null,
        moderation_until = null,
        moderation_note = null,
        updated_at = now()
    where id = target_user_id
    returning * into changed_profile;
  else
    update public.profiles
    set moderation_type = action_type,
        moderation_until = now() + make_interval(mins => duration_minutes),
        moderation_note = nullif(trim(moderation_reason), ''),
        updated_at = now()
    where id = target_user_id
    returning * into changed_profile;
  end if;

  if changed_profile.id is null then
    raise exception 'Profile not found';
  end if;

  perform public.write_audit_event(
    case when action_type = 'clear' then 'moderation_cleared' else 'moderation_applied' end,
    target_user_id,
    jsonb_build_object(
      'moderation_type', action_type,
      'duration_minutes', duration_minutes,
      'note', moderation_reason,
      'until', changed_profile.moderation_until
    )
  );

  return changed_profile;
end;
$$;

revoke all on function public.admin_set_member_moderation(uuid, text, integer, text) from public;
grant execute on function public.admin_set_member_moderation(uuid, text, integer, text) to authenticated;

create or replace function public.submit_moderation_appeal(appeal_reason text)
returns public.moderation_appeals
language plpgsql
security definer set search_path = public
as $$
declare
  new_appeal public.moderation_appeals;
begin
  if auth.uid() is null then
    raise exception 'You must be signed in';
  end if;
  if nullif(trim(appeal_reason), '') is null then
    raise exception 'Appeal reason is required';
  end if;

  insert into public.moderation_appeals (user_id, reason)
  values (auth.uid(), trim(appeal_reason))
  returning * into new_appeal;

  perform public.write_audit_event(
    'moderation_appeal_submitted',
    auth.uid(),
    jsonb_build_object('appeal_id', new_appeal.id, 'reason', new_appeal.reason)
  );
  return new_appeal;
end;
$$;

